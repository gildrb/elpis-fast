"""Independent Python reference of the ext 8201 fused-MLP schedule table.

Origin: the PersistMLP work copied this file (gen_table.py) into the repo
without change of logic.
Role: bend/mlp_m16_sched_diff.py compares its stdout with the Bend emitter
bend/MLP_M16_SCHED_TABLE.bend.
It prints the exact header text to stdout.
Usage: python3 -B bend/gen/mlp_m16_sched_ref.py > exl3_mlp_m16_sched.h
"""

import sys

G, PF = 164, 8
K1, N1, K2, N2 = 5120, 17408, 17408, 5120
GW = 512
KT1, NG1 = K1 // 16, N1 // GW
KT2, NG2 = K2 // 16, N2 // GW
T1 = 2 * NG1 * KT1
T2 = NG2 * KT2
NP = NG1  # gate/up column pairs = down k-groups of 512 columns
PKT = GW // 16  # down k-tiles per pair (32)


def start(b: int, tot: int) -> int:
    """Split tot items over G blocks.

    Args:
        b: The block.
        tot: The item count.

    Returns:
        The first item of block b.

    """
    return b * tot // G


def owner(x: int, tot: int) -> int:
    """Find the owner block of an item.

    Args:
        x: The item.
        tot: The item count.

    Returns:
        The block that owns item x of tot.

    """
    return ((x + 1) * G + tot - 1) // tot - 1


def nc(g: int, kt: int, tot: int) -> int:
    """Count the contributors of a group.

    Args:
        g: The group.
        kt: The tiles per group.
        tot: The item count.

    Returns:
        How many blocks contribute to group g of kt tiles.

    """
    return owner((g + 1) * kt - 1, tot) - owner(g * kt, tot) + 1


def slice_pairs(v: int) -> list[int]:
    """List the pairs a down-projection block touches.

    Args:
        v: The block.

    Returns:
        The pairs block v touches, in first-touch order.

    """
    s, e = start(v, T2), start(v + 1, T2)
    out: list[int] = []
    for it in range(s, e):
        p = (it % KT2) // PKT
        if p not in out:
            out.append(p)
    return out


def build() -> tuple[list[list[int]], list[list[int]], list[int], int, int]:
    """Build the schedule.

    Returns:
        The block rows, pair rows, wait list and the two max contributors.

    """
    blocks: list[list[int]] = []
    waits: list[int] = []
    fin_pair = [slice_pairs(b)[0] for b in range(G)]
    k = [fin_pair.count(p) for p in range(NP)]
    for b in range(G):
        s1, e1 = start(b, T1), start(b + 1, T1)
        v = b
        s2, e2 = start(v, T2), start(v + 1, T2)
        p = fin_pair[b]
        rank = fin_pair[:b].count(p)
        w = slice_pairs(v)
        blocks.append([
            s1,
            e1 - s1,
            v,
            s2,
            e2 - s2,
            (e1 - s1) % PF,
            p,
            rank,
            k[p],
            len(waits),
            len(w),
        ])
        waits.extend(w)
    pairs: list[list[int]] = []
    for p in range(NP):
        w2 = sum(p in slice_pairs(v) for v in range(G))
        pairs.append([
            8 * nc(p, KT1, T1),
            8 * nc(NP + p, KT1, T1),
            8 * k[p],
            8 * k[p],
            w2,
        ])
    mc1 = max(nc(g, KT1, T1) for g in range(2 * NG1))
    mc2 = max(nc(g, KT2, T2) for g in range(NG2))
    return blocks, pairs, waits, mc1, mc2


def render() -> str:
    """Render the header.

    Returns:
        The exact header text.

    """
    blocks, pairs, waits, mc1, mc2 = build()
    lines = [
        (
            "// Generated by bend/MLP_M16_SCHED_TABLE.bend "
            "(ext 8201 fused MLP schedule); do not edit."
        ),
        f"#define EXL3_MLP_SCHED_G {G}",
        f"#define EXL3_MLP_SCHED_PF {PF}",
        f"#define EXL3_MLP_SCHED_K1 {K1}",
        f"#define EXL3_MLP_SCHED_N1 {N1}",
        f"#define EXL3_MLP_SCHED_K2 {K2}",
        f"#define EXL3_MLP_SCHED_N2 {N2}",
        f"#define EXL3_MLP_SCHED_PAIRS {NP}",
        "#define EXL3_MLP_SCHED_BF 11",
        "#define EXL3_MLP_SCHED_PFLD 5",
        f"#define EXL3_MLP_SCHED_NWAIT {len(waits)}",
        f"#define EXL3_MLP_SCHED_MC1 {mc1}",
        f"#define EXL3_MLP_SCHED_MC2 {mc2}",
        f"static const unsigned short exl3_mlp_sched_block[{G} * 11] = {{",
    ]
    lines += ["".join(f"{x}," for x in r) for r in blocks]
    lines += ["};", f"static const unsigned short exl3_mlp_sched_pair[{NP} * 5] = {{"]
    lines += ["".join(f"{x}," for x in r) for r in pairs]
    lines += [
        "};",
        f"static const unsigned short exl3_mlp_sched_wait[{len(waits)}] = {{",
    ]
    lines += ["".join(f"{x}," for x in waits[r[9] : r[9] + r[10]]) for r in blocks]
    lines += ["};"]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render())

"""Generate the tree acceptance table programs.

Outputs, written into the existing directory OUT:
- OUT/exl3_tree_table.bend: the shared rendering templates.
- OUT/EXL3_TREE_ACCEPT.bend: the production program (production leaves).
- OUT/EXL3_TREE_ACCEPT_SPEC.bend: the reference program (list reference).

Inputs: none. The script is deterministic. It does not read the repository.

Regenerate and check the tracked files (from the repository root):
    mkdir /tmp/x && python3 -I -B bend/gen/gen_table.py --out-dir /tmp/x
    for f in exl3_tree_table EXL3_TREE_ACCEPT EXL3_TREE_ACCEPT_SPEC; do
        cmp /tmp/x/$f.bend bend/$f.bend
    done

Origin: gen_table.py of the S4 tree acceptance harness. The header line of
bend/exl3_tree_table.bend names it. Only the output paths and the explicit UTF-8
encoding changed. The three outputs are sources of the acceptor identity that
bend/exl3_build.py records, so the header stays byte-identical.
"""

import argparse
from pathlib import Path

parser = argparse.ArgumentParser(
    description="Generate the tree acceptance table programs."
)
parser.add_argument(
    "--out-dir", required=True, type=Path, help="existing output directory"
)
out = parser.parse_args().out_dir
if not out.is_dir():
    msg = f"gen_table: FAIL: {out} is not a directory"
    raise SystemExit(msg)
LAST_LEVEL = 7
R = range(1, 8)
T = ", ".join(f"t{i}" for i in range(8))
X = ", ".join(f"x{i}" for i in R)
Q = ", ".join(f"q{i}" for i in R)
QA = ", ".join(f"+q{i}: Nat" for i in R)

ACC_T = (
    " -> ".join(["Nat"] * 7)
    + " -> Nat -> Nat -> Nat -> U32 -> U32 -> U32 -> U32 -> "
    + " -> ".join(["U32"] * 8)
    + " -> "
    + " -> ".join(["U32"] * 7)
    + " -> "
    + "Spec.TreeVerdict"
)
DER_T = " -> ".join(["Nat"] * 7) + " -> List<&2, Nat>"
TPL = f"~acc: {ACC_T}, ~der: {DER_T}"
TARGS = "~acc, ~der"


def tv(i: int) -> str:
    """Return the verify id of row ``i`` in the table.

    Args:
        i: Row index.

    Returns:
        The verify id as text.

    """
    return f"{100 + i}"


def call(budget: str, cp: str, ns: str, s: list[str], xs: list[str]) -> str:
    """Render one ``acc`` call for the table.

    Args:
        budget: Budget argument text.
        cp: Checkpoint argument text.
        ns: Stop count argument text.
        s: Stop row argument texts.
        xs: Draft argument texts.

    Returns:
        The rendered call.

    """
    ts = ", ".join(tv(i) for i in range(8))
    return f"acc({Q}, {budget}, {cp}, {ns}, {', '.join(s)}, {ts}, {', '.join(xs)})"


table: list[str] = []
w = table.append
w("""# Rendering of the tree acceptance table (DESIGN.md §3(d) admission), shared by
# EXL3_TREE_ACCEPT.bend (production leaves) and EXL3_TREE_ACCEPT_SPEC.bend (list
# reference) through templates, so both print byte-identical text exactly when
# the two implementations agree on every cell.
#
# One line per legal parent array q1..q7 (q_r < r, lexicographic):
#   "S <q1..q7> <D> <W> <R>"
# D: the 128 derive bytes, hex. Verify id of row r is 100 + r.
# W: for match mask m = 0..127 (bit r - 1 set: token of row r equals its parent's
#    verify id, else 99), budget 262144, checkpoint 0, no stop slots used (the
#    slots hold 100..103): the verdict glyph. This covers every path the walk can take.
# R: mask 127, the chain rules along the lowest-child path: budget 1..9 x
#    checkpoint 0..7; one stop slot holding row r's verify id (r = 0..7); stop
#    counts 0..4 over slots [107, 106, 105, 104].
# Glyph: chr(64 + 2 * count + eos) then chr(48 + last).
#
# Generated by the S4 harness (gen_table.py).
import Base
import ./exl3_tree_accept_spec.bend as Spec

def hex_digit(+n: Nat) -> Char:
  Char.from_u32((U32.add(U32.from_nat(n), \
U32.mul(U32.from_nat(Nat.div(n, 10n)), 39)) + 48 : U32))

def hex_bytes(bs: List<&2, Nat>, rest: String) -> String:
  match bs:
    case Nil{}:
      rest
    case +b <> more:
      SCon{hex_digit(Nat.div(b, 16n)), \
SCon{hex_digit(Nat.mod(b, 16n)), hex_bytes(more, rest)}}

def glyph(v: Spec.TreeVerdict, rest: String) -> String:
  match v:
    case Spec.TreeVerdict{n, e, l}:
      match e:
        case False{}:
          SCon{Char.from_u32((U32.from_nat(Nat.double(n)) + 64 : U32)),
            SCon{Char.from_u32((U32.from_nat(l) + 48 : U32)), rest}}
        case True{}:
          SCon{Char.from_u32((U32.from_nat(Nat.double(n)) + 65 : U32)),
            SCon{Char.from_u32((U32.from_nat(l) + 48 : U32)), rest}}

def digit(n: Nat, rest: String) -> String:
  SCon{Char.from_u32((U32.from_nat(n) + 48 : U32)), rest}

# Parent's verify id for a matching token.
def vid(q: Nat) -> U32:
  (U32.from_nat(q) + 100 : U32)
""")

# W cells: x7 outermost (bit 6 most significant) .. x1 innermost.
for k in range(1, 8):
    fixed = ", ".join(f"+x{i}: U32" for i in range(k + 1, 8))
    fixed_a = ", ".join(f"x{i}" for i in range(k + 1, 8))
    head = (
        f"def wcells{k}({TPL}, {QA}"
        + (f", {fixed}" if fixed else "")
        + ", rest: String) -> String:"
    )
    w(head)
    if k == 1:
        xs_miss = ["99"] + [f"x{i}" for i in range(2, 8)]
        xs_hit = ["vid(q1)"] + [f"x{i}" for i in range(2, 8)]
        s = ["100", "101", "102", "103"]
        w(f"  glyph({call('262144n', '0n', '0n', s, xs_miss)},")
        w(f"    glyph({call('262144n', '0n', '0n', s, xs_hit)}, rest))")
    else:
        pre = f"{TARGS}, {Q}"
        miss = ", ".join(["99"] + ([fixed_a] if fixed_a else []))
        hitv = ", ".join([f"vid(q{k})"] + ([fixed_a] if fixed_a else []))
        w(f"  wcells{k - 1}({pre}, {miss},")
        w(f"    wcells{k - 1}({pre}, {hitv}, rest))")
    w("")

# R cells, by recursion over budgets / checkpoints, stop rows and stop counts.
FULL = ", ".join(f"vid(q{i})" for i in R)
TS = ", ".join(tv(i) for i in range(8))
w(f"""def rcp({TPL}, n: Nat, +b: Nat, +cp: Nat, {QA}, rest: String) -> String:
  match n:
    case 0n:
      rest
    case 1n+m:
      glyph(acc({Q}, b, cp, 0n, 100, 101, 102, 103, {TS}, {FULL}),
        rcp({TARGS}, m, b, 1n+cp, {Q}, rest))

def rbud({TPL}, n: Nat, +b: Nat, {QA}, rest: String) -> String:
  match n:
    case 0n:
      rest
    case 1n+m:
      rcp({TARGS}, 8n, b, 0n, {Q}, rbud({TARGS}, m, 1n+b, {Q}, rest))

def rstop({TPL}, n: Nat, +r: Nat, {QA}, rest: String) -> String:
  match n:
    case 0n:
      rest
    case 1n+m:
      glyph(acc({Q}, 262144n, 0n, 1n, vid(r), 107, 106, 105, {TS}, {FULL}),
        rstop({TARGS}, m, 1n+r, {Q}, rest))

def rns({TPL}, n: Nat, +k: Nat, {QA}, rest: String) -> String:
  match n:
    case 0n:
      rest
    case 1n+m:
      glyph(acc({Q}, 262144n, 0n, k, 107, 106, 105, 104, {TS}, {FULL}),
        rns({TARGS}, m, 1n+k, {Q}, rest))

def rcells({TPL}, {QA}, rest: String) -> String:
  rbud({TARGS}, 9n, 1n, {Q}, rstop({TARGS}, 8n, 0n, {Q}, \
rns({TARGS}, 5n, 0n, {Q}, rest)))
""")

w(f"""def line({TPL}, {QA}) -> String:
  "S " ++ digit(q1, digit(q2, digit(q3, digit(q4, \
digit(q5, digit(q6, digit(q7, " ")))))))
    ++ hex_bytes(der({Q}), " ")
    ++ wcells7({TARGS}, {Q}, " ")
    ++ rcells({TARGS}, {Q}, "")
""")

# enumeration levels: level k iterates q_k over 0..k-1
for k in range(7, 0, -1):
    prev = ", ".join(f"+q{i}: Nat" for i in range(1, k))
    prev_a = ", ".join(f"q{i}" for i in range(1, k))
    head = (
        f"def level{k}({TPL}, count: Nat, +v: Nat"
        + (f", {prev}" if prev else "")
        + ") -> IO(Unit):"
    )
    w(head)
    w("  match count:")
    w("    case 0n:")
    w("      IO.pure(Unit, Unit{})")
    w("    case 1n+more:")
    w("      do IO<Unit>:")
    args = (prev_a + ", " if prev_a else "") + "v"
    if k == LAST_LEVEL:
        w(f"        IO.print(line({TARGS}, {args}))")
    else:
        w(f"        level{k + 1}({TARGS}, {k + 1}n, 0n, {args})")
    w(f"        level{k}({TARGS}, more, 1n+v" + (f", {prev_a}" if prev_a else "") + ")")
    w("")

w(f"""def table({TPL}) -> IO(Unit):
  do IO<Unit>:
    IO.print("EXL3_TREE_ACCEPT_V1")
    level1({TARGS}, 1n, 0n)
    IO.print("END_EXL3_TREE_ACCEPT")
""")
(out / "exl3_tree_table.bend").write_text("\n".join(table), encoding="utf-8")

TA = ", ".join(f"t{i}: U32" for i in range(8))
XA = ", ".join(f"x{i}: U32" for i in R)
QW = ", ".join(f"q{i}: Nat" for i in R)
SA = "budget: Nat, checkpoint: Nat, ns: Nat, s0: U32, s1: U32, s2: U32, s3: U32"
(out / "EXL3_TREE_ACCEPT.bend").write_text(
    f"""# Production program: its unchanged emitted C is compiled into the serving
# shared library, whose glue calls only the scalar leaves Impl.accept_tree and
# Impl.derive. main renders the tree acceptance table (exl3_tree_table.bend)
# through those leaves; it must be byte-identical to EXL3_TREE_ACCEPT_SPEC.bend's.
import Base
import ./exl3_tree_accept.bend as Impl
import ./exl3_tree_accept_spec.bend as Spec
import ./exl3_tree_table.bend as Table

def acc({QW}, {SA}, {TA}, {XA}) -> Spec.TreeVerdict:
  Impl.accept_tree(budget, checkpoint, ns, s0, s1, s2, s3, {T}, {X}, {Q})

def der({QW}) -> List<&2, Nat>:
  Impl.bytes(Impl.derive({Q}))

def main() -> IO(Unit):
  Table.table(~acc, ~der)
""",
    encoding="utf-8",
)
(out / "EXL3_TREE_ACCEPT_SPEC.bend").write_text(
    f"""# Reference program: renders the tree acceptance table (exl3_tree_table.bend)
# through the list reference exl3_tree_accept_spec.bend. The build pins its
# output and requires EXL3_TREE_ACCEPT.bend to print the same bytes.
import Base
import ./exl3_tree_accept_spec.bend as Spec
import ./exl3_tree_table.bend as Table

def acc({QW}, {SA}, {TA}, {XA}) -> Spec.TreeVerdict:
  Spec.accept_tree([{", ".join(f"Spec.Node{{q{i}, x{i}}}" for i in R)}], [{T}],
    List.take(&2, U32, [s0, s1, s2, s3], ns), budget, checkpoint)

def der({QW}) -> List<&2, Nat>:
  Spec.derive([{Q}])

def main() -> IO(Unit):
  Table.table(~acc, ~der)
""",
    encoding="utf-8",
)

"""Shared slot-weighted split-K partition (m16g fix and 8205). Reference + header generator.

Origin: the M16gEff work copied this file (wpart.py) into the repo without change of logic.
Role: bend/gen/m16_wsched_ref.py imports it for the partition formulas.

Blocks b < n_sm have weight w0, blocks b >= n_sm have weight w1 (integers >= 1); G = grid (n_sm <= G <= 2 n_sm):
    W(b)     = w0 * min(b, n_sm) + w1 * max(b - n_sm, 0)
    start(b) = (total * W(b)) // W(G)                      (int64; (1, 1) is v2's b * total // G)
    owner(x) = max{b : start(b) <= x}                       (block owning iteration x, 0 <= x < total)
Domain: w0, w1 >= 1; every slice nonempty, i.e. start(b + 1) > start(b) for all b < G (checked by `valid`).
owner in closed form (what the CUDA side implements): with s1 = start(n_sm),
    x < s1:  b = ((x + 1) * W(G) + total - 1) // total - 1 over weights w0      -> b = (ceil((x+1) * WG / total) - 1) // w0
    x >= s1: same for the w1 segment, offset by n_sm.
`owner_closed` is that expression; `self_test` checks it against the definition.

    python3 bend/gen/wpart.py self-test
    python3 bend/gen/wpart.py header NAME total G n_sm w0 w1      # prints #defines (starts are recomputed on the device)
"""

from __future__ import annotations

import random
import sys


def W(b: int, n_sm: int, w0: int, w1: int) -> int:
    return w0 * min(b, n_sm) + w1 * max(b - n_sm, 0)


def start(b: int, total: int, G: int, n_sm: int, w0: int, w1: int) -> int:
    return total * W(b, n_sm, w0, w1) // W(G, n_sm, w0, w1)


def owner(x: int, total: int, G: int, n_sm: int, w0: int, w1: int) -> int:
    lo, hi = 0, G - 1  # max b with start(b) <= x (start monotone, start(0) = 0)
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if start(mid, total, G, n_sm, w0, w1) <= x:
            lo = mid
        else:
            hi = mid - 1
    return lo


def owner_closed(x: int, total: int, G: int, n_sm: int, w0: int, w1: int) -> int:
    WG = W(G, n_sm, w0, w1)
    # smallest weight prefix P with total * P // WG > x is P = ((x + 1) * WG + total - 1) // total; owner = the
    # block whose prefix range [W(b), W(b + 1)) contains P - 1
    P = ((x + 1) * WG + total - 1) // total - 1
    if P < w0 * n_sm:
        return P // w0
    return n_sm + (P - w0 * n_sm) // w1


def max_contrib(groups: int, KT: int, G: int, n_sm: int, w0: int, w1: int) -> int:
    total = groups * KT
    return max(
        owner_closed((g + 1) * KT - 1, total, G, n_sm, w0, w1)
        - owner_closed(g * KT, total, G, n_sm, w0, w1)
        + 1
        for g in range(groups)
    )


def valid(total: int, G: int, n_sm: int, w0: int, w1: int) -> bool:
    return (
        w0 >= 1
        and w1 >= 1
        and n_sm <= G <= 2 * n_sm
        and all(
            start(b + 1, total, G, n_sm, w0, w1) > start(b, total, G, n_sm, w0, w1)
            for b in range(G)
        )
    )


def self_test() -> None:
    rnd = random.Random(8205)
    cases = [
        (32 * 320, 164, 82, 100, 93),
        (28 * 320, 164, 82, 100, 93),
        (10 * 384, 164, 82, 100, 80),
        (34 * 320 * 2, 164, 82, 100, 97),
        (32 * 320, 164, 82, 1, 1),
        (32 * 320, 82, 82, 1, 1),
    ]
    for _ in range(300):
        n_sm = rnd.randint(1, 100)
        G = rnd.randint(n_sm, 2 * n_sm)
        cases.append((
            rnd.randint(G, 20000),
            G,
            n_sm,
            rnd.randint(1, 120),
            rnd.randint(1, 120),
        ))
    n = 0
    for total, G, n_sm, w0, w1 in cases:
        if not valid(total, G, n_sm, w0, w1):
            continue
        n += 1
        assert (
            start(0, total, G, n_sm, w0, w1) == 0
            and start(G, total, G, n_sm, w0, w1) == total
        )
        if w0 == w1:
            assert all(
                start(b, total, G, n_sm, w0, w1) == b * total // G for b in range(G + 1)
            ), "(w, w) must be v2"
        xs = range(total) if total <= 4000 else rnd.sample(range(total), 4000)
        for x in xs:
            b = owner_closed(x, total, G, n_sm, w0, w1)
            assert b == owner(x, total, G, n_sm, w0, w1), (total, G, n_sm, w0, w1, x)
            assert (
                start(b, total, G, n_sm, w0, w1)
                <= x
                < start(b + 1, total, G, n_sm, w0, w1)
            )
    print(
        f"self-test OK: {n} valid configurations; owner_closed == max{{b: start(b) <= x}}; (w, w) == v2"
    )


def header(name: str, total: int, G: int, n_sm: int, w0: int, w1: int) -> str:
    assert valid(total, G, n_sm, w0, w1), (
        "weights outside the domain (a slice would be empty)"
    )
    return (
        f"// Generated by wpart.py; slot-weighted partition {name}: total {total}, G {G}, n_sm {n_sm}\n"
        f"#define {name}_W0 {w0}\n#define {name}_W1 {w1}\n#define {name}_NSM {n_sm}\n"
    )


if __name__ == "__main__":
    if sys.argv[1:2] == ["self-test"]:
        self_test()
    elif sys.argv[1:2] == ["header"]:
        print(header(sys.argv[2], *map(int, sys.argv[3:8])), end="")
    else:
        sys.exit(__doc__)
